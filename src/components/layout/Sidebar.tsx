import { useState } from 'react';
import { NavLink, useNavigate } from 'react-router-dom';
import { useAuth } from '../../context';
import { ROUTES, APP_NAME } from '../../config/constants';
import { cn } from '../../utils';
import { getInitials } from '../../utils/helpers';

const adminNavItems = [
  { to: ROUTES.ADMIN_DASHBOARD, label: 'Dashboard', icon: HomeIcon },
  { to: ROUTES.ADMIN_PRODUCTS, label: 'Productos', icon: BoxIcon },
  { to: ROUTES.ADMIN_CATEGORIES, label: 'Categorías', icon: TagIcon },
  { to: ROUTES.ADMIN_SALES, label: 'Ventas', icon: ShoppingCartIcon },
  { to: ROUTES.ADMIN_INVOICES, label: 'Facturas', icon: DocumentIcon },
  { to: ROUTES.ADMIN_CUSTOMERS, label: 'Clientes', icon: UsersIcon },
  { to: ROUTES.ADMIN_DEBTS, label: 'Deudas', icon: CreditCardIcon },
  { to: ROUTES.ADMIN_PAYMENT_REQUESTS, label: 'Solicitudes', icon: ClipboardIcon },
  { to: ROUTES.ADMIN_REPORTS, label: 'Reportes', icon: ChartIcon },
  { to: ROUTES.ADMIN_SETTINGS, label: 'Configuración', icon: SettingsIcon },
];

interface SidebarProps {
  isOpen: boolean;
  onClose: () => void;
}

export function Sidebar({ isOpen, onClose }: SidebarProps) {
  const { profile, signOut } = useAuth();
  const navigate = useNavigate();
  const [isCollapsed, setIsCollapsed] = useState(false);

  const handleSignOut = async () => {
    await signOut();
    navigate(ROUTES.LOGIN);
  };

  return (
    <>
      {/* Overlay móvil */}
      {isOpen && (
        <div
          className="fixed inset-0 bg-slate-400/30 z-20 lg:hidden"
          onClick={onClose}
        />
      )}

      {/* Sidebar */}
      <aside
        className={cn(
          'fixed inset-y-0 left-0 z-30 flex flex-col bg-white text-slate-700 border-r border-sky-100 transition-all duration-300 shadow-sm',
          isCollapsed ? 'w-16' : 'w-64',
          isOpen ? 'translate-x-0' : '-translate-x-full lg:translate-x-0'
        )}
      >
        {/* Logo */}
        <div className="flex items-center justify-between h-16 px-4 border-b border-sky-100">
          {!isCollapsed && (
            <span className="text-xl font-bold text-sky-700">{APP_NAME}</span>
          )}
          <button
            onClick={() => setIsCollapsed(!isCollapsed)}
            className="hidden lg:block p-1 rounded-lg text-slate-500 hover:bg-sky-50 hover:text-sky-600"
          >
            <svg
              className={cn('w-5 h-5 transition-transform', isCollapsed && 'rotate-180')}
              fill="none"
              stroke="currentColor"
              viewBox="0 0 24 24"
            >
              <path
                strokeLinecap="round"
                strokeLinejoin="round"
                strokeWidth={2}
                d="M11 19l-7-7 7-7m8 14l-7-7 7-7"
              />
            </svg>
          </button>
          <button onClick={onClose} className="lg:hidden p-1 rounded-lg text-slate-500 hover:bg-sky-50">
            <svg className="w-6 h-6" fill="none" stroke="currentColor" viewBox="0 0 24 24">
              <path strokeLinecap="round" strokeLinejoin="round" strokeWidth={2} d="M6 18L18 6M6 6l12 12" />
            </svg>
          </button>
        </div>

        {/* Navigation */}
        <nav className="flex-1 overflow-y-auto py-4">
          <ul className="space-y-1 px-2">
            {adminNavItems.map((item) => (
              <li key={item.to}>
                <NavLink
                  to={item.to}
                  onClick={onClose}
                  className={({ isActive }) =>
                    cn(
                      'flex items-center gap-3 px-3 py-2 rounded-lg transition-colors',
                      isActive
                        ? 'bg-sky-100 text-sky-700 font-medium'
                        : 'text-slate-600 hover:bg-sky-50 hover:text-sky-600'
                    )
                  }
                >
                  <item.icon className="w-5 h-5 flex-shrink-0" />
                  {!isCollapsed && <span>{item.label}</span>}
                </NavLink>
              </li>
            ))}
          </ul>
        </nav>

        {/* User info */}
        <div className="border-t border-sky-100 p-4">
          <div className="flex items-center gap-3">
            <div className="w-10 h-10 rounded-full bg-sky-500 flex items-center justify-center flex-shrink-0 text-white text-sm font-medium">
              {profile ? getInitials(profile.name) : '?'}
            </div>
            {!isCollapsed && (
              <div className="flex-1 min-w-0">
                <p className="text-sm font-medium truncate text-slate-800">{profile?.name}</p>
                <p className="text-xs text-slate-500 truncate">{profile?.email}</p>
              </div>
            )}
          </div>
          {!isCollapsed && (
            <button
              onClick={handleSignOut}
              className="mt-3 w-full flex items-center justify-center gap-2 px-3 py-2 text-sm text-slate-600 hover:text-sky-600 hover:bg-sky-50 rounded-lg transition-colors"
            >
              <LogoutIcon className="w-4 h-4" />
              Cerrar sesión
            </button>
          )}
        </div>
      </aside>
    </>
  );
}

